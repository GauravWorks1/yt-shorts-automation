"""
Google Flow to YouTube Upload Bridge Automation.
Connects Google Flow video generation script directly to YouTube upload automation.
Supports immediate execution, pipeline bridging, and folder watcher daemon mode.
"""

import argparse
import json
import os
import time
from pathlib import Path
from typing import Dict, Optional

import config
from core.metadata_engine import MetadataEngine
from core.thumbnail_engine import ThumbnailEngine
from integrations.google_flow_connector import GoogleFlowConnector
from integrations.youtube_uploader import YouTubeUploader


class FlowToYouTubeBridge:
    """
    Connects Google Flow video generation output to automated YouTube upload.
    Validates renders, pairs thumbnails and metadata, and performs seamless publishing.
    """

    def __init__(self):
        self.flow_connector = GoogleFlowConnector()
        self.uploader = YouTubeUploader()
        self.thumbnail_engine = ThumbnailEngine()

    def process_and_upload(
        self,
        video_file: Path,
        topic_info: Dict,
        script_info: Dict,
        thumbnail_file: Optional[Path] = None,
        privacy: str = "public",
        publish_at: Optional[str] = None
    ) -> Dict:
        """
        Takes a video generated by Google Flow (or local flow renderer),
        generates SEO metadata and thumbnail if needed, and uploads directly to YouTube.
        """
        video_file = Path(video_file)
        if not video_file.exists():
            raise FileNotFoundError(f"Google Flow video output not found at: {video_file}")

        print(f"\n[FlowToYouTubeBridge] Bridging video {video_file.name} to YouTube...")

        # 1. Generate Metadata
        metadata = MetadataEngine.generate_metadata(topic_info, script_info)
        print(f"[FlowToYouTubeBridge] Metadata generated: {metadata['title']}")

        # 2. Ensure Thumbnail Exists
        if not thumbnail_file or not os.path.exists(thumbnail_file):
            thumb_path = config.OUTPUT_DIR / f"{video_file.stem}_thumb.jpg"
            print(f"[FlowToYouTubeBridge] Generating CTR thumbnail at: {thumb_path}")
            top_t = script_info.get("scenes", [{}])[0].get("top_text", metadata["title"])
            bot_t = script_info.get("scenes", [{}])[-1].get("bottom_text", "WATCH TILL END!")
            self.thumbnail_engine.generate_thumbnail(
                top_text=top_t,
                bottom_text=bot_t,
                output_path=thumb_path
            )
            thumbnail_file = thumb_path

        # 3. Upload to YouTube
        upload_result = self.uploader.upload_short(
            video_path=video_file,
            title=metadata["title"],
            description=metadata["description"],
            tags=metadata["tags"],
            thumbnail_path=thumbnail_file,
            category_id=metadata["category_id"],
            privacy_status=privacy,
            publish_at=publish_at
        )

        print(f"\n🎉 [FlowToYouTubeBridge] SUCCESS! Video published via automation:")
        print(f"🔗 URL: {upload_result['url']}")
        print(f"🎬 Title: {upload_result['title']}")
        print(f"🔒 Privacy: {upload_result['status']}")
        return upload_result

    def watch_flow_and_auto_upload(self, watch_dir: Optional[Path] = None, poll_interval: int = 5):
        """
        Daemon Mode: Continuously monitors Google Flow output directory.
        Whenever a new video appears (e.g. *.mp4 with matching *.json metadata),
        it automatically uploads it to YouTube and moves it to an archive folder.
        """
        target_dir = Path(watch_dir or config.OUTPUT_DIR)
        archive_dir = target_dir / "uploaded_archive"
        archive_dir.mkdir(parents=True, exist_ok=True)

        print(f"[FlowToYouTubeBridge] 🚀 Watcher daemon started on: {target_dir}")
        print("Waiting for completed Google Flow videos to auto-upload... (Press Ctrl+C to stop)")

        processed_files = set()

        try:
            while True:
                # Find mp4 files in target dir (excluding archive)
                for video_p in target_dir.glob("flow_*_completed.mp4"):
                    if video_p.name in processed_files:
                        continue

                    print(f"\n[FlowToYouTubeBridge] Detected new Google Flow render: {video_p.name}")
                    # Look for companion metadata json
                    meta_p = video_p.with_name(video_p.name.replace("_completed.mp4", "_manifest.json"))
                    topic_data = {}
                    script_data = {}

                    if meta_p.exists():
                        try:
                            with open(meta_p, "r", encoding="utf-8") as f:
                                manifest = json.load(f)
                                topic_data = {"title": manifest.get("video_metadata", {}).get("title", "Viral Short")}
                                script_data = {"title": topic_data["title"], "scenes": manifest.get("scenes", [])}
                        except Exception as e:
                            print(f"Could not read manifest {meta_p}: {e}")

                    if not topic_data:
                        topic_data = {"title": video_p.stem.replace("_", " ").title()}
                        script_data = {"title": topic_data["title"], "scenes": []}

                    # Upload
                    try:
                        self.process_and_upload(
                            video_file=video_p,
                            topic_info=topic_data,
                            script_info=script_data,
                            privacy=config.YOUTUBE_DEFAULT_PRIVACY
                        )
                        processed_files.add(video_p.name)

                        # Move to archive
                        time.sleep(2)
                        video_p.rename(archive_dir / video_p.name)
                        if meta_p.exists():
                            meta_p.rename(archive_dir / meta_p.name)
                        print(f"[FlowToYouTubeBridge] Moved {video_p.name} to archive.")

                    except Exception as err:
                        print(f"[FlowToYouTubeBridge] Upload error for {video_p.name}: {err}")
                        processed_files.add(video_p.name)

                time.sleep(poll_interval)

        except KeyboardInterrupt:
            print("\n[FlowToYouTubeBridge] Watcher daemon stopped.")


def main():
    parser = argparse.ArgumentParser(description="Bridge Google Flow video generation to YouTube Upload automation.")
    parser.add_argument("--video", type=str, help="Path to Google Flow generated video file")
    parser.add_argument("--manifest", type=str, help="Path to script/manifest JSON file")
    parser.add_argument("--thumbnail", type=str, help="Path to custom thumbnail JPG")
    parser.add_argument("--privacy", type=str, default="public", choices=["public", "unlisted", "private"])
    parser.add_argument("--watch", action="store_true", help="Run in daemon mode watching output directory")
    args = parser.parse_args()

    bridge = FlowToYouTubeBridge()

    if args.watch:
        bridge.watch_flow_and_auto_upload()
    elif args.video:
        video_path = Path(args.video)
        manifest_data = {}
        if args.manifest and os.path.exists(args.manifest):
            with open(args.manifest, "r", encoding="utf-8") as f:
                manifest_data = json.load(f)
        
        topic = {"title": manifest_data.get("title", video_path.stem)}
        script = manifest_data or {"title": topic["title"], "scenes": []}

        bridge.process_and_upload(
            video_file=video_path,
            topic_info=topic,
            script_info=script,
            thumbnail_file=Path(args.thumbnail) if args.thumbnail else None,
            privacy=args.privacy
        )
    else:
        print("Usage:")
        print("  python flow_to_youtube_bridge.py --video path/to/video.mp4")
        print("  python flow_to_youtube_bridge.py --watch")


if __name__ == "__main__":
    main()
